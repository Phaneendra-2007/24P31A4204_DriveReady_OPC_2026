MENU = {
    "plum cake": 500,
    "chocolate cake": 650,
    "cupcake": 80
}

def get_price(item: str, qty: int = 1) -> int:
    """
    Return the total price of a product.

    Args:
        item: Product name.
        qty: Number of items.

    Returns:
        Total price in rupees.
    """
    item = item.lower()

    if item not in MENU:
        raise ValueError("Product not available")

    if qty <= 0:
        raise ValueError("Quantity must be positive")

    return MENU[item] * qty


print(get_price("chocolate cake", 2))

def is_available(item: str) -> bool:
    """
    Check whether a product is available in the menu.

    Args:
        item: Product name.

    Returns:
        True if available, otherwise False.
    """
    return item.lower() in MENU


