from langchain_core.prompts import ChatPromptTemplate, MessagesPlaceholder
from langchain_core.output_parsers import StrOutputParser

SYSTEM = """
ROLE: You are the friendly assistant for Sweet Crumbs Home Bakery.

FACTS:
Plum cake Rs 500.
Chocolate cake Rs 650.
Cupcake Rs 80 each.
Orders need 24 hours' notice.
All cakes have eggless versions.

RULES:
Never promise a delivery time or place.
If information is not available, say
"I'll check with the owner."
Calculate totals carefully.

FORMAT:
Under 50 words.
Friendly.
Reply in English or Telugu matching the customer.
"""

prompt = ChatPromptTemplate.from_messages([
    ("system", SYSTEM),
    MessagesPlaceholder("history"),
    ("human", "{question}")
])

chain = prompt | llm | StrOutputParser()

history = []

def ask(question: str) -> str:
    answer = chain.invoke({
        "history": history,
        "question": question
    })

    history.extend([
        ("human", question),
        ("ai", answer)
    ])

    return answer

print(ask("Hi, I am Ravi. Do you make eggless cakes?"))
print(ask("What is my name?"))

