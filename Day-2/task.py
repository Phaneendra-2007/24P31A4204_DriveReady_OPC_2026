def get_service_info(service_name):
    """
    Returns the price of a tailoring service.

    Args:
        service_name: Name of the required tailoring service.

    Returns:
        Service price or a message if unavailable.
    """
    service_name = service_name.lower().replace(" ", "_")

    if service_name in catalogue:
        return f"The price is Rs. {catalogue[service_name]}."

    return "Sorry, this service is not available in our catalogue."


