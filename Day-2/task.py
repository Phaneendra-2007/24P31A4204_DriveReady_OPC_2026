def classify_message(new_message):
    messages = [
        {
            "role": "system",
            "content": """
You are a customer message classifier for VV Tailors.

Classify every customer message into exactly one category:
order, question, or complaint.

Return ONLY the category name in lowercase.
"""
        },

        # Three examples (few-shot learning)
        {"role": "user", "content": "I need a blouse stitched."},
        {"role": "assistant", "content": "order"},

        {"role": "user", "content": "How much does pant alteration cost?"},
        {"role": "assistant", "content": "question"},

        {"role": "user", "content": "My dress stitching is not good."},
        {"role": "assistant", "content": "complaint"},

        # New customer message
        {"role": "user", "content": new_message}
    ]

    response = client.chat.completions.create(
        model=MODEL,
        messages=messages,
        temperature=0
    )

    return response.choices[0].message.content.strip().lower()


