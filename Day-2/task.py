MENU = {
    "plum cake": 500,
    "chocolate cake": 650,
    "cupcake": 80
}

def get_price(item: str, qty: int = 1) -> int:
    """
    Return the total price of the selected bakery item.

    Args:
        item: Name of the bakery product.
        qty: Number of items required.

    Returns:
        Total price in rupees.
    """
    item = item.lower().strip()

    if item not in MENU:
        raise ValueError("Item is not available in the menu.")

    return MENU[item] * qty


print(get_price("chocolate cake", 2))

