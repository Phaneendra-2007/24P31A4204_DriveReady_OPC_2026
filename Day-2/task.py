history = [
    {"role": "system", "content":
     "You are a friendly bakery assistant. Remember customer details from the conversation."}
]

MAX_TURNS = 2

def chat(user_text):
    history.append({
        "role": "user",
        "content": user_text
    })

    # Keep only the latest two messages
    recent = [history[0]] + history[1:][-MAX_TURNS:]

    response = client.chat.completions.create(
        model="openai/gpt-oss-20b",
        messages=recent,
        temperature=0.3
    )

    reply = response.choices[0].message.content

    history.append({
        "role": "assistant",
        "content": reply
    })

    return reply


print("Bot:", chat("My name is Ravi."))
