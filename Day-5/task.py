class RepairBooking(BaseModel):
    """A laptop repair booking extracted from a customer's chat message."""
    name: str = Field(description="Customer's first name")
    service: Literal["screen replacement", "battery replacement", "keyboard repair", "os installation"]
    devices: int = Field(ge=1)
    drop_date: str
    urgent: bool

@tool
def get_repair_cost(service: str, devices: int = 1) -> str:
    """Get the total repair cost in rupees for a laptop repair service and number of devices.

    Args:
        service: Repair service name, e.g. "screen replacement", "battery replacement", "keyboard repair", or "os installation"
        devices: Number of laptops needing the repair (default is 1)
    """
    cost = SERVICES.get(service.lower().strip())
    if cost is None:
        return f"'{service}' is not a standard service. Available services: {', '.join(SERVICES)}."
    return f"{devices} x {service} = Rs {cost * devices}"

@tool
def check_repair_slot(day: str) -> str:
    """Check ByteFix Electronics Repair shop hours and technician availability for a day of the week, e.g. "saturday"."""
    status = TECHNICIAN_SLOTS.get(day.lower().strip())
    return f"{day.capitalize()}: {status}" if status else f"'{day}' is not a valid day of the week."

@tool
def log_repair_booking(name: str, service: str, devices: int, drop_date: str, urgent: bool) -> str:
    """Save a confirmed laptop repair booking to the ByteFix Repair Bookings record.
    Use ONLY when the customer has provided their name, service, number of devices, and drop-off date."""
    try:
        booking = RepairBooking(
            name=name,
            service=service.lower().strip(),
            devices=devices,
            drop_date=drop_date,
            urgent=urgent
        )
    except Exception as e:
        return f"Could not save booking: {e}. Ask the customer to clarify."

    total = SERVICES[booking.service] * booking.devices
    # Note: If Google Sheets `ws_biz` is authenticated in Colab, uncomment below:
    # ws_biz.append_row([booking.name, booking.service, booking.devices, booking.drop_date, "yes" if booking.urgent else "no", total])
    return f"Saved booking: {booking.devices} x {booking.service} for {booking.name} on {booking.drop_date}, Total: Rs {total}."

