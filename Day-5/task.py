agent = create_agent(
    model=llm,
    tools=[get_repair_cost, check_repair_slot, log_repair_booking, search_bytefix_faq],
    system_prompt=SYSTEM_FINAL,
    checkpointer=InMemorySaver()
)

def chat(thread_id: str, text: str) -> str:
    config = {"configurable": {"thread_id": thread_id}}
    try:
        result = agent.invoke({"messages": [{"role": "user", "content": text}]}, config)
        return result["messages"][-1].content
    except Exception as e:
        print("Agent error:", e)
        return "Sorry, I'm a little busy right now. Please try again in a minute."

